"""Exercise starter initialization in disposable repositories, without network access.

Setup runs with a PATH of its own: the system tools it needs, and fakes of Pixi, prok, and the tools
around prok that record their calls. Nothing is installed, downloaded, or logged in to.

The initializer removes this file from generated projects along with setup.sh.
"""

from pathlib import Path
import re
import shlex
import shutil
import subprocess
import tomllib

import pytest


STARTER = Path(__file__).resolve().parents[1]
PROK_URL = "https://prok.example.invalid"
GENERATED = "<!-- Generated by prok emit. Do not edit. -->\n"
SYSTEM_TOOLS = (
    "bash basename cat chmod cp dirname env file find git grep head ls mkdir mktemp mv "
    "realpath rm rmdir sed sh tr touch uname"
).split()

# Each fake logs its call as "<tool> <arguments>", fails on the call named in SETUP_TEST_FAIL_COMMAND,
# and otherwise exits with the status of its last command.
FAKE_START = (
    "#!/bin/sh\n"
    'printf "%s %s\\n" "${0##*/}" "$*" >> "$SETUP_TEST_COMMAND_LOG"\n'
    'if [ "${0##*/} $*" = "$SETUP_TEST_FAIL_COMMAND" ]; then exit 42; fi\n'
)
FAKES = {
    "pixi": 'if [ "$1" = install ] && [ ! -f pixi.lock ]; then\n'
    '    printf "# Fresh project lock\\n" > pixi.lock\n'
    "fi\n",
    # What setup relies on from prok: init writes the pointer, the ignore rules and its commit hook; a login
    # needs a Google login; the generated files need a login; the plugin steps are what prok would print.
    "prok": 'case "$1" in\n'
    "init)\n"
    "    mkdir -p .prok\n"
    '    printf "url: %s\\nproject: %s\\n" "$3" "$5" > .prok/central.yaml\n'
    '    printf "\\n# prok: generated files and personal files\\n/AGENTS.md\\n/CLAUDE.md\\n" >> .gitignore\n'
    '    printf "#!/bin/sh\\n# Written by prok. It refuses a commit.\\nprok validate\\n" > .git/hooks/pre-commit\n'
    "    ;;\n"
    'whoami) [ -f "$HOME/prok-login" ] ;;\n'
    'login) [ -f "$HOME/google-login" ] && touch "$HOME/prok-login" ||'
    ' { echo "prok: no Google login found on this machine" >&2; exit 2; } ;;\n'
    'emit-agent-instructions) [ -f "$HOME/prok-login" ] && printf "%s\\n" "$SETUP_TEST_GENERATED" > AGENTS.md ;;\n'
    "install-agent-plugin)\n"
    '    echo "For Claude Code to take the plugin of prok on this machine, run this and start Claude Code again:"\n'
    '    echo "  claude plugin marketplace add ~/.local/share/prok/claude"\n'
    '    echo "  claude plugin install prok@prok-local"\n'
    "    ;;\n"
    "esac\n",
    "gcloud": 'touch "$HOME/google-login"\n',
    "claude": "",
    "node": 'echo "${SETUP_TEST_NODE_MAJOR:-24}"\n',
    "npm": 'cp "$SETUP_TEST_PROK" "${0%/*}/prok"\n',
    "gh": 'if [ "$1" = release ]; then touch "$8/prok.tgz"; fi\n',
}


def install_fake(bin_dir: Path, tool: str) -> Path:
    fake = bin_dir / tool
    fake.write_text(FAKE_START + FAKES[tool] + "exit $?\n")
    fake.chmod(0o755)
    return fake


