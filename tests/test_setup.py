@pytest.mark.parametrize(("prok", "readme"), [("y", "y"), ("y", "n"), ("n", "y")])
def test_first_agent_session_finds_every_placeholder(
    starter_copy: tuple[Path, dict[str, str], Path], prok: str, readme: str
) -> None:
    project, env, _ = starter_copy
    answers = ["n", "n", prok, *([""] if prok == "y" else []), "y", readme, "n"]
    run_setup(project, env, answers)

    instructions = ".prok/instructions.md" if prok == "y" else "AGENTS.md"
    marked = {
        str(path.relative_to(project))
        for path in project.rglob("*")
        if ".git" not in path.relative_to(project).parts
        and path.is_file()
        and "TEMPLATE:" in path.read_text(errors="ignore")
    }
    expected = {"pyproject.toml", instructions} | (
        {"README.md"} if readme == "y" else set()
    )
    assert marked == expected
    # The first line tells a new agent how to find the placeholders.
    instruction = (project / instructions).read_text().splitlines()[0]
    command = re.search(r"`(git grep [^`]+)`", instruction).group(1)
    found = subprocess.run(
        shlex.split(command), cwd=project, capture_output=True, text=True
    ).stdout
    assert {line.split(":", 1)[0] for line in found.splitlines()} == expected


def test_setup_installs_prok_where_it_is_missing(
    starter_copy: tuple[Path, dict[str, str], Path],
) -> None:
    project, env, command_log = starter_copy
    prok = bin_of(env) / "prok"
    env["SETUP_TEST_PROK"] = str(prok.rename(prok.with_name("prok-release")))
    run_setup(project, env, ["", "n"])

    checked, downloaded = calls(command_log, "gh")
    assert checked == "gh api repos/pymc-labs/prok --silent"
    assert downloaded.startswith(
        "gh release download -R pymc-labs/prok -p prok.tgz -D "
    )
    assert calls(command_log, "npm")[0].startswith("npm install -g ")
    assert_prok(project, True)


@pytest.mark.parametrize(
    "missing", ["old-node", "no-gh", "no-access", "declined"], ids=str
)
def test_setup_continues_without_prok_where_it_cannot_be_installed(
    starter_copy: tuple[Path, dict[str, str], Path], missing: str
) -> None:
    project, env, command_log = starter_copy
    (bin_of(env) / "prok").unlink()
    if missing == "old-node":
        env["SETUP_TEST_NODE_MAJOR"] = "22"
    if missing == "no-gh":
        (bin_of(env) / "gh").unlink()
    if missing == "no-access":
        env["SETUP_TEST_FAIL_COMMAND"] = "gh api repos/pymc-labs/prok --silent"
    # Where prok cannot be installed, setup asks for no project name.
    answers = ["n", "n", "y"] + (["n"] if missing == "declined" else [])
    result = run_setup(project, env, [*answers, "y", "y", "n"])

    assert "Continuing without prok" in result.stdout
    assert calls(command_log, "npm") == []
    assert_prok(project, False)
    assert_decision_hub(project, True, prok=False)


