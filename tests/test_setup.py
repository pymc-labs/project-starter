@pytest.mark.parametrize(("prok", "readme"), [("y", "y"), ("y", "n"), ("n", "y")])
def test_first_agent_session_finds_every_placeholder(
    starter_copy: tuple[Path, dict[str, str], Path], prok: str, readme: str
) -> None:
    project, env, _ = starter_copy
    answers = ["n", "n", prok, *([""] if prok == "y" else []), "y", readme, "n"]
    run_setup(project, env, answers)

    instructions = ".prok/instructions.md" if prok == "y" else "AGENTS.md"
    # The generated AGENTS.md repeats the instructions, but Git ignores it, and so does the search.
    ignored = set(
        subprocess.check_output(
            ["git", "ls-files", "--others", "--ignored", "--exclude-standard"],
            cwd=project,
            text=True,
        ).split()
    )
    marked = {
        str(path.relative_to(project))
        for path in project.rglob("*")
        if ".git" not in path.relative_to(project).parts
        and path.is_file()
        and "TEMPLATE:" in path.read_text(errors="ignore")
    } - ignored
    expected = {"pyproject.toml", instructions} | (
        {"README.md"} if readme == "y" else set()
    )
    assert marked == expected
    # The first line tells a new agent how to find the placeholders.
    instruction = (project / instructions).read_text().splitlines()[0]
    command = re.search(r"`(git grep [^`]+)`", instruction).group(1)
    found = subprocess.run(
        shlex.split(command), cwd=project, capture_output=True, text=True
    ).stdout
    assert {line.split(":", 1)[0] for line in found.splitlines()} == expected


